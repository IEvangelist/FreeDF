using AdoBye.Samples.Kit;
using static AdoBye.Samples.Kit.Helpers;
using static AdoBye.Samples.Kit.Theme;

namespace AdoBye.Samples.Gen;

static class Gen01
{
    public const string Out = "01-spec-showcase.pdf";

    static readonly (string Num, string Name, string File)[] Tiles =
    [
        ("02", "Standard 14 fonts", "02-standard-14-fonts.pdf"), ("03", "Typography", "03-typography-embedded.pdf"),
        ("04", "Text render modes", "04-text-render-modes.pdf"), ("05", "Vector graphics", "05-vector-graphics.pdf"),
        ("06", "Patterns & shadings", "06-patterns-shadings.pdf"), ("07", "Transparency", "07-transparency.pdf"),
        ("08", "Colour spaces", "08-colour-spaces.pdf"), ("09", "Images", "09-images.pdf"),
        ("10", "Annotations", "10-annotations.pdf"), ("11", "AcroForm", "11-acroform.pdf"),
        ("12", "Navigation", "12-navigation.pdf"), ("13", "Page boxes", "13-page-boxes-rotation.pdf"),
        ("14", "Embedded files", "14-embedded-files.pdf"), ("15", "Optional content", "15-optional-content.pdf"),
        ("16", "TrueType", "16-truetype-specimen.pdf"), ("17", "Encryption", "17-encrypted-user-password.pdf"),
        ("19", "Tagged PDF", "19-tagged-accessible.pdf"), ("20", "Report", "20-report.pdf"),
        ("21", "Brochure", "21-brochure.pdf"), ("22", "Invoice", "22-invoice.pdf"),
        ("23", "Résumé", "23-resume.pdf"), ("24", "Poster", "24-poster.pdf"),
        ("25", "Dashboard", "25-dashboard-charts.pdf"), ("26", "Repacked", "26-repacked-object-streams.pdf"),
    ];

    static readonly string[] Accents = [P["indigo"], P["violet"], P["sky"], P["teal"], P["amber"], P["rose"], P["emerald"], P["orange"]];

    public static void Build(string path)
    {
        var d = new Doc("PDF 2.0 spec showcase", author: "Pdf sample generator", subject: "Cover and index of the sample suite", keywords: "ISO 32000-2, samples, showcase", lang: "en-US");
        var t = new Faces(d);
        var (w, h) = A4;
        var pg = d.Page(w, h);
        Background(pg, P["ink"]);

        pg.Save(); pg.Rect(0, h - 330, w, 330); pg.Clip();
        pg.Sh(Axial(0, h, w, h - 330, [(0, "#312E81"), (0.55, "#6D28D9"), (1, "#BE185D")]));
        pg.Save(); pg.Gs(("ca", 0.06)); pg.Fill("#FFFFFF");
        for (var k = 0; k < 14; k++) { pg.Circle(w - 40 - k * 6, h - 90 + k * 3, 280 - k * 19); pg.FillPath(); }
        pg.Restore();
        pg.Restore();
        LogoMark(pg, M, h - 96, 34, a: "#A5B4FC", b: "#F0ABFC");
        pg.Text(t.SansB, 9, M + 48, h - 84, "ISO 32000-2  ·  PDF 2.0", color: "#E0E7FF", tracking: 2.4, kern: false);
        pg.Text(t.SerifB, 54, M, h - 190, "Everything a", color: "#FFFFFF");
        pg.Text(t.SerifB, 54, M, h - 250, "page can do.", color: "#FFFFFF");
        pg.Text(t.SerifI, 14, M, h - 292, "A suite of twenty-five example documents, each built from raw operators.", color: "#E9D5FF");

        const int cols = 4;
        const double gap = 8, th = 54;
        var tw = (w - 2 * M - (cols - 1) * gap) / cols;
        var y0 = h - 330 - 40;
        pg.Text(t.SansB, 8, M, y0, "THE COLLECTION", color: "#A5B4FC", tracking: 2, kern: false);
        for (var i = 0; i < Tiles.Length; i++)
        {
            var (num, name, target) = Tiles[i];
            int r = i / cols, c = i % cols;
            var x = M + c * (tw + gap);
            var y = y0 - 18 - (r + 1) * th - r * gap;
            Color acc = Accents[i % Accents.Length];
            Box(pg, x, y, tw, th, fill: "#151C33", stroke: "#26304F", r: 8);
            pg.Save(); pg.Fill(acc); pg.RRect(x, y + th - 3, tw, 3, 1.5); pg.FillPath(); pg.Restore();
            pg.Text(t.SerifB, 20, x + 12, y + 26, num, color: acc);
            pg.Text(t.SansB, 9.5, x + 12, y + 10, name, color: "#E2E8F0");
            Glyph(pg, acc, i % 6, x + tw - 28, y + 28);
            pg.AddAnnot($"<< /Type /Annot /Subtype /Link /Rect [{K.N(x)} {K.N(y)} {K.N(x + tw)} {K.N(y + th)}] /Border [0 0 0] /A << /S /GoToR /F ({target}) /D [0 /Fit] /NewWindow true >> /Contents ({name}) >>");
        }

        pg.Text(t.Sans, 8.5, M, 54, "Each tile links to its sample file (GoToR). Open this document next to the other PDFs in the samples folder.", color: "#94A3B8");
        pg.Text(t.Mono, 8, M, 36, "generated by tools/AdoBye.Samples  ·  repeatable  ·  no stock images", color: "#64748B");
        d.Save(path);
    }

    static void Glyph(Page pg, Color acc, int k, double gx, double gy)
    {
        pg.Save(); pg.Stroke(acc); pg.Width(1.4); pg.Fill(acc); pg.Cap(1); pg.Join(1);
        switch (k)
        {
            case 0: pg.Rect(gx - 9, gy - 9, 18, 18); pg.StrokePath(); break;
            case 1: pg.Circle(gx, gy, 10); pg.StrokePath(); pg.Circle(gx, gy, 3.5); pg.FillPath(); break;
            case 2: pg.Move(gx - 11, gy - 8); pg.Line(gx, gy + 10); pg.Line(gx + 11, gy - 8); pg.Close(); pg.StrokePath(); break;
            case 3: pg.Move(gx - 11, gy); pg.Curve(gx - 5, gy + 14, gx + 5, gy - 14, gx + 11, gy); pg.StrokePath(); break;
            case 4: pg.Save(); pg.Gs(("ca", 0.6)); pg.Circle(gx - 4, gy, 8); pg.FillPath(); pg.Circle(gx + 4, gy, 8); pg.FillPath(); pg.Restore(); break;
            default:
                for (var j = 0; j < 3; j++) { pg.Move(gx - 10, gy - 7 + j * 7); pg.Line(gx + 10, gy - 7 + j * 7); pg.StrokePath(); }
                break;
        }
        pg.Restore();
    }
}
